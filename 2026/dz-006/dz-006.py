# На вход программы подаётся число k <= 15. Создайте список, содержащий все степени двойки от 2**0 до 2**k, то есть список [2, 4, 8, 16, 32, 64... 2**k].

ans = []
k = int(input("введи число k(<=15): "))
if k < 0 or k > 16:
    print("Введите число от 0 до 15!")
    exit(0)

for i in range(0, k):
    ans.append(2 ** i)

print(ans)
