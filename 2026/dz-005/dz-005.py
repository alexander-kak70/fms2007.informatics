# 15. Напишите подпрограмму def prog_15() поиска всех трёхзначных чисел, делящихся на 7, сумма цифр которых также кратна 7.
def prog_15():
    result = []
    for i in range(100, 1000):
        if i % 7 == 0 and sum0(i) % 7 == 0:
            result.append(i)
    return result


# функция находящая сумму цифр числа
def sum0(number):
    r = 0  # остаток от деления
    result = 0
    while number > 0:
        r = number % 10
        number = int(number / 10)
        result += r

    return result


