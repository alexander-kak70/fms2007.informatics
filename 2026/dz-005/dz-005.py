# 13. Напишите подпрограмму def prog_13(a, b), которая возвращает сумму целых положительных чисел, больших 20, меньших 100, кратных 3 и заканчивающихся на 2, 4 или 8.
# непонятно зачем нужны a и b - сделаем их границами интервала
def prog_13(a=20, b=100):
    result = 0
    for i in range(a + 1, b):
        if i > 0 and i % 3 == 0 and i % 10 in (2, 4, 8):
            result += i
    return result


