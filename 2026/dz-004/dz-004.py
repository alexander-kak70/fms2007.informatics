# Шифр кодового замка является
# двузначным числом. Известно, что произведение цифр этого числа,
# сложенное с их суммой, равно 23. Запишите в список все двузначные числа,
# которые могли быть шифром кодового замка.
for a in range(1, 10):
    for b in range(0, 10):
        if a + b + a * b == 23:
            print(str(a) + str(b))
